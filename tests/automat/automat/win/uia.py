"""The program's windows as a screen reader sees them: Windows UI Automation.

Qt publishes its widgets through UI Automation; an element's name is its visible text
(menu items without '&'). This module only reads: names, kinds, rectangles and states.
All actions go through real input (automat.win.input).

COM: create one Uia object per thread; it initialises COM for that thread.
"""

import ctypes
import sys
import threading
import time

# A UI Automation client belongs in a multithreaded apartment (Microsoft Docs, "Understanding
# Threading Issues"): a single-threaded one that does not pump messages can hold up the
# program it reads. comtypes initialises COM for the importing thread with sys.coinit_flags.
if not hasattr(sys, "coinit_flags"):
    sys.coinit_flags = 0  # COINIT_MULTITHREADED

import comtypes  # noqa: E402
import comtypes.client  # noqa: E402

comtypes.client.GetModule("UIAutomationCore.dll")
from comtypes.gen import UIAutomationClient as UIA  # noqa: E402  (generated by GetModule)

from automat import stopping  # noqa: E402

# Tree scopes
SCOPE_CHILDREN = 2
SCOPE_DESCENDANTS = 4

# Property ids
P_BOUNDING_RECTANGLE = 30001
P_PROCESS_ID = 30002
P_CONTROL_TYPE = 30003
P_NAME = 30005
P_HAS_KEYBOARD_FOCUS = 30008
P_IS_ENABLED = 30010
P_AUTOMATION_ID = 30011
P_CLASS_NAME = 30012
P_NATIVE_WINDOW_HANDLE = 30020
P_IS_OFFSCREEN = 30022
P_HELP_TEXT = 30013
P_FULL_DESCRIPTION = 30159  # Windows 10 1703 and later
P_IS_EXPAND_AVAILABLE = 30028
P_IS_TOGGLE_AVAILABLE = 30041
P_IS_SELECTION_ITEM_AVAILABLE = 30036
P_TOGGLE_STATE = 30086
P_IS_SELECTED = 30079
P_EXPAND_STATE = 30070

# Pattern ids
PAT_SELECTION = 10001
PAT_VALUE = 10002
PAT_RANGE_VALUE = 10003
PAT_EXPAND_COLLAPSE = 10005
PAT_GRID = 10006
PAT_GRID_ITEM = 10007
PAT_SELECTION_ITEM = 10010
PAT_TABLE = 10012
PAT_TEXT = 10014
PAT_TOGGLE = 10015

CONTROL_TYPES = {
    50000: "Button", 50001: "Calendar", 50002: "CheckBox", 50003: "ComboBox", 50004: "Edit",
    50005: "Hyperlink", 50006: "Image", 50007: "ListItem", 50008: "List", 50009: "Menu",
    50010: "MenuBar", 50011: "MenuItem", 50012: "ProgressBar", 50013: "RadioButton",
    50014: "ScrollBar", 50015: "Slider", 50016: "Spinner", 50017: "StatusBar", 50018: "Tab",
    50019: "TabItem", 50020: "Text", 50021: "ToolBar", 50022: "ToolTip", 50023: "Tree",
    50024: "TreeItem", 50025: "Custom", 50026: "Group", 50027: "Thumb", 50028: "DataGrid",
    50029: "DataItem", 50030: "Document", 50031: "SplitButton", 50032: "Window", 50033: "Pane",
    50034: "Header", 50035: "HeaderItem", 50036: "Table", 50037: "TitleBar", 50038: "Separator",
}
_TYPE_IDS = {v: k for k, v in CONTROL_TYPES.items()}

# The roles a scenario may name, and the UI Automation kinds each one covers.
ROLES = {
    # A checkable button is a check box for UI Automation, and an exclusive one (one of a
    # group) a radio button (qtbase 6.9 simplewidgets.cpp, QAccessibleButton::role); for a
    # person all of them are buttons.
    "button": ("Button", "SplitButton", "CheckBox", "RadioButton"),
    "check_box": ("CheckBox",),
    "radio": ("RadioButton",),
    "combo_box": ("ComboBox",),
    "edit": ("Edit", "Document"),
    "document": ("Document", "Edit"),
    "list": ("List", "DataGrid", "Table", "Tree"),
    "list_item": ("ListItem", "DataItem"),
    "tree": ("Tree",),
    "tree_item": ("TreeItem",),
    "tab": ("TabItem",),
    "menu_item": ("MenuItem",),
    "menu": ("Menu", "MenuBar"),
    "text": ("Text",),
    "slider": ("Slider",),
    "spinner": ("Spinner",),
    "group": ("Group",),
    "window": ("Window",),
    "toolbar": ("ToolBar",),
    "cell": ("DataItem", "ListItem", "TreeItem"),
    "header": ("HeaderItem",),
}

TOGGLE_STATES = {0: "off", 1: "on", 2: "indeterminate"}

_local = threading.local()


def _com_init() -> None:
    if getattr(_local, "com", False):
        return
    try:
        comtypes.CoInitializeEx(comtypes.COINIT_MULTITHREADED)
    except OSError:
        pass  # this thread already has COM (for example the main thread after importing comtypes)
    _local.com = True


def wrap(uia, raw):
    """An Element, or None when UI Automation gave a NULL pointer (Qt does that, for example,
    for a cell past the last column of a table)."""
    return Element(uia, raw) if raw else None


class Element:
    """One UI Automation element; every property is read fresh."""

    def __init__(self, uia: "Uia", raw):
        self._uia = uia
        self.raw = raw

    def _get(self, attribute, default=None):
        try:
            return getattr(self.raw, attribute)
        except (comtypes.COMError, ValueError):  # ValueError: the element is a NULL pointer
            return default

    @property
    def name(self) -> str:
        return self._get("CurrentName", "") or ""

    @property
    def control_type(self) -> str:
        return CONTROL_TYPES.get(self._get("CurrentControlType", 0), "Unknown")

    @property
    def automation_id(self) -> str:
        return self._get("CurrentAutomationId", "") or ""

    @property
    def class_name(self) -> str:
        return self._get("CurrentClassName", "") or ""

    @property
    def description(self) -> str:
        """What a screen reader says after the name; Qt gives an empty field's placeholder
        text here (QAccessibleLineEdit, Description), which is what a person reads in it."""
        try:
            value = self.raw.GetCurrentPropertyValue(P_FULL_DESCRIPTION)
        except (comtypes.COMError, ValueError, AttributeError):
            value = None
        if not value:
            value = self._get("CurrentHelpText", "")
        return value if isinstance(value, str) else ""

    @property
    def enabled(self) -> bool:
        return bool(self._get("CurrentIsEnabled", False))

    @property
    def offscreen(self) -> bool:
        return bool(self._get("CurrentIsOffscreen", True))

    @property
    def has_focus(self) -> bool:
        return bool(self._get("CurrentHasKeyboardFocus", False))

    @property
    def hwnd(self) -> int:
        return int(self._get("CurrentNativeWindowHandle", 0) or 0)

    @property
    def pid(self) -> int:
        return int(self._get("CurrentProcessId", 0) or 0)

    @property
    def rect(self) -> tuple:
        r = self._get("CurrentBoundingRectangle")
        if r is None:
            return (0, 0, 0, 0)
        return (r.left, r.top, r.right, r.bottom)

    @property
    def center(self) -> tuple:
        left, top, right, bottom = self.rect
        return ((left + right) // 2, (top + bottom) // 2)

    def visible(self) -> bool:
        left, top, right, bottom = self.rect
        return not self.offscreen and right > left and bottom > top

    def _pattern(self, pattern_id, interface):
        try:
            unknown = self.raw.GetCurrentPattern(pattern_id)
        except comtypes.COMError:
            return None
        if not unknown:
            return None
        try:
            return unknown.QueryInterface(interface)
        except comtypes.COMError:
            return None

    def value(self):
        pattern = self._pattern(PAT_VALUE, UIA.IUIAutomationValuePattern)
        if pattern is None:
            return None
        try:
            return pattern.CurrentValue
        except comtypes.COMError:
            return None

    def range_value(self):
        pattern = self._pattern(PAT_RANGE_VALUE, UIA.IUIAutomationRangeValuePattern)
        return None if pattern is None else pattern.CurrentValue

    def toggle_state(self):
        pattern = self._pattern(PAT_TOGGLE, UIA.IUIAutomationTogglePattern)
        return None if pattern is None else TOGGLE_STATES.get(pattern.CurrentToggleState)

    def is_selected(self):
        pattern = self._pattern(PAT_SELECTION_ITEM, UIA.IUIAutomationSelectionItemPattern)
        return None if pattern is None else bool(pattern.CurrentIsSelected)

    def expanded(self):
        pattern = self._pattern(PAT_EXPAND_COLLAPSE, UIA.IUIAutomationExpandCollapsePattern)
        return None if pattern is None else pattern.CurrentExpandCollapseState in (1, 2)

    def text(self):
        """The whole text of a document-like element (Text pattern), or None."""
        pattern = self._pattern(PAT_TEXT, UIA.IUIAutomationTextPattern)
        if pattern is None:
            return None
        try:
            return pattern.DocumentRange.GetText(-1)
        except comtypes.COMError:
            return None

    def selected_text(self):
        pattern = self._pattern(PAT_TEXT, UIA.IUIAutomationTextPattern)
        if pattern is None:
            return None
        ranges = pattern.GetSelection()
        return "".join(ranges.GetElement(i).GetText(-1) for i in range(ranges.Length))

    def grid_position(self):
        pattern = self._pattern(PAT_GRID_ITEM, UIA.IUIAutomationGridItemPattern)
        return None if pattern is None else (pattern.CurrentRow, pattern.CurrentColumn)

    def column_headers(self) -> list:
        pattern = self._pattern(PAT_TABLE, UIA.IUIAutomationTablePattern)
        if pattern is None:
            return []
        array = pattern.GetCurrentColumnHeaders()
        found = (wrap(self._uia, array.GetElement(i)) for i in range(array.Length))
        return [e for e in found if e is not None]

    def cell(self, row: int, column: int):
        pattern = self._pattern(PAT_GRID, UIA.IUIAutomationGridPattern)
        if pattern is None:
            return None
        try:
            return wrap(self._uia, pattern.GetItem(row, column))
        except (comtypes.COMError, ValueError):
            return None

    def children(self) -> list:
        return self._uia.find_all(self, scope=SCOPE_CHILDREN)

    def find_all(self, name=None, kinds=None, scope=SCOPE_DESCENDANTS) -> list:
        return self._uia.find_all(self, name=name, kinds=kinds, scope=scope)

    def describe(self) -> dict:
        item = {"name": self.name, "type": self.control_type, "rect": list(self.rect),
                "enabled": self.enabled, "automation_id": self.automation_id,
                "class": self.class_name}
        description = self.description
        if description:
            item["description"] = description
        return item

    def __repr__(self) -> str:
        return f"<{self.control_type} {self.name!r} {self.rect}>"


class Uia:
    """The UI Automation client of the current thread."""

    def __init__(self):
        _com_init()
        self.client = comtypes.CoCreateInstance(UIA.CUIAutomation._reg_clsid_,
                                                interface=UIA.IUIAutomation,
                                                clsctx=comtypes.CLSCTX_INPROC_SERVER)
        self.root = Element(self, self.client.GetRootElement())

    def _condition(self, name=None, kinds=None, pid=None):
        conditions = []
        if name is not None:
            conditions.append(self.client.CreatePropertyCondition(P_NAME, name))
        if kinds:
            ids = [_TYPE_IDS[k] for k in kinds]
            kind_conditions = [self.client.CreatePropertyCondition(P_CONTROL_TYPE, i) for i in ids]
            condition = kind_conditions[0]
            for other in kind_conditions[1:]:
                condition = self.client.CreateOrCondition(condition, other)
            conditions.append(condition)
        if pid is not None:
            conditions.append(self.client.CreatePropertyCondition(P_PROCESS_ID, pid))
        if not conditions:
            return self.client.CreateTrueCondition()
        condition = conditions[0]
        for other in conditions[1:]:
            condition = self.client.CreateAndCondition(condition, other)
        return condition

    def find_all(self, parent: Element, name=None, kinds=None, pid=None,
                 scope=SCOPE_DESCENDANTS) -> list:
        try:
            array = parent.raw.FindAll(scope, self._condition(name, kinds, pid))
        except comtypes.COMError:
            return []
        if not array:
            return []
        return [Element(self, array.GetElement(i)) for i in range(array.Length)]

    def snapshot(self, parent: Element, kinds=None, scope=SCOPE_DESCENDANTS) -> list:
        """[(name, control type, offscreen, Element)] of every matching element, with the
        properties read in one pass (a cache request) instead of one call per property."""
        request = self.client.CreateCacheRequest()
        for prop in (P_NAME, P_CONTROL_TYPE, P_IS_OFFSCREEN):
            request.AddProperty(prop)
        try:
            array = parent.raw.FindAllBuildCache(scope, self._condition(kinds=kinds), request)
        except comtypes.COMError:
            return []
        if not array:
            return []
        out = []
        for i in range(array.Length):
            raw = array.GetElement(i)
            try:
                out.append((raw.CachedName or "", CONTROL_TYPES.get(raw.CachedControlType, "Unknown"),
                            bool(raw.CachedIsOffscreen), Element(self, raw)))
            except comtypes.COMError:
                continue
        return out

    def controls(self, parent: Element, kinds=None, scope=SCOPE_DESCENDANTS) -> list:
        """[{"name", "type", "rect", "enabled", "offscreen", "toggle", "selected", "expandable",
        "expanded", "element"}] of every matching element, read in one pass (a cache request)."""
        request = self.client.CreateCacheRequest()
        for prop in (P_NAME, P_CONTROL_TYPE, P_IS_OFFSCREEN, P_BOUNDING_RECTANGLE, P_IS_ENABLED,
                     P_IS_TOGGLE_AVAILABLE, P_TOGGLE_STATE, P_IS_SELECTION_ITEM_AVAILABLE, P_IS_SELECTED,
                     P_IS_EXPAND_AVAILABLE, P_EXPAND_STATE):
            request.AddProperty(prop)
        try:
            array = parent.raw.FindAllBuildCache(scope, self._condition(kinds=kinds), request)
        except comtypes.COMError:
            return []
        if not array:
            return []
        out = []
        for i in range(array.Length):
            raw = array.GetElement(i)
            try:
                r = raw.CachedBoundingRectangle
                item = {"name": raw.CachedName or "", "type": CONTROL_TYPES.get(raw.CachedControlType, "Unknown"),
                        "rect": (r.left, r.top, r.right, r.bottom), "enabled": bool(raw.CachedIsEnabled),
                        "offscreen": bool(raw.CachedIsOffscreen), "toggle": None, "selected": None,
                        "expandable": False, "expanded": None, "element": Element(self, raw)}
                if raw.GetCachedPropertyValue(P_IS_TOGGLE_AVAILABLE) is True:
                    item["toggle"] = TOGGLE_STATES.get(int(raw.GetCachedPropertyValue(P_TOGGLE_STATE)))
                if raw.GetCachedPropertyValue(P_IS_SELECTION_ITEM_AVAILABLE) is True:
                    item["selected"] = bool(raw.GetCachedPropertyValue(P_IS_SELECTED))
                if raw.GetCachedPropertyValue(P_IS_EXPAND_AVAILABLE) is True:
                    item["expandable"] = True
                    item["expanded"] = int(raw.GetCachedPropertyValue(P_EXPAND_STATE)) in (1, 2)
            except (comtypes.COMError, TypeError, ValueError):
                continue
            out.append(item)
        return out

    def top_windows(self, pid: int) -> list:
        """All top-level windows of the process, as UI Automation sees them (menus included)."""
        return self.find_all(self.root, pid=pid, scope=SCOPE_CHILDREN)

    def from_handle(self, hwnd: int):
        try:
            return wrap(self, self.client.ElementFromHandle(hwnd))
        except (comtypes.COMError, ValueError):
            return None

    def focused(self):
        try:
            return wrap(self, self.client.GetFocusedElement())
        except (comtypes.COMError, ValueError):
            return None

    def dump(self, element: Element, depth: int = 6, limit: int = 4000) -> list:
        """The element and its subtree as nested dicts (for reports and for writing scenarios)."""
        count = [0]

        def walk(node: Element, level: int):
            count[0] += 1
            item = node.describe()
            for state, getter in (("toggle", node.toggle_state), ("value", node.value)):
                current = getter()
                if current is not None:
                    item[state] = current
            if level < depth and count[0] < limit:
                kids = [walk(child, level + 1) for child in node.children()]
                if kids:
                    item["children"] = kids
            return item

        return [walk(element, 0)]


def wait_until(probe, timeout: float, interval: float = 0.01):
    """Call probe() until it returns something true; returns (result, moment) or (None, None)."""
    deadline = time.perf_counter() + timeout
    while True:
        stopping.check()
        result = probe()
        moment = time.perf_counter()
        if result:
            return result, moment
        if moment >= deadline:
            return None, None
        time.sleep(interval)


def flatten(tree: list) -> list:
    out = []
    stack = list(tree)
    while stack:
        node = stack.pop(0)
        out.append(node)
        stack[0:0] = node.get("children", [])
    return out


